"""Generate the course's three synthetic datasets, reproducibly.

    python datasets/generate.py               # writes datasets/generated/
    python datasets/generate.py --seed 7      # a different draw, same shape
    python datasets/generate.py --check       # verify the manifest matches the files

Every row is invented. The generator is the provenance: no downloaded file, no
real person, no scraped record. The same seed produces byte-identical CSV files
on every platform because floats are rounded and written with a fixed format.

Files written:

* ``raviride_trips.csv``   -- completed trips, for the ETA model
* ``study_support.csv``    -- synthetic student-support risk records
* ``equipment_sensors.csv``-- synthetic machine readings with a failure label
* ``manifest.json``        -- row counts, columns, SHA-256 of each file
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import random
from dataclasses import dataclass
from datetime import date, timedelta
from pathlib import Path

DEFAULT_SEED = 20260101
DEFAULT_OUT = Path(__file__).resolve().parent / "generated"

LICENCE = "CC0-1.0 (synthetic data generated by this script; no source data)"


@dataclass(frozen=True)
class Dataset:
    name: str
    filename: str
    description: str
    columns: list[str]
    rows: list[list[object]]


def _csv_cell(value: object) -> str:
    if isinstance(value, float):
        return f"{value:.4f}"
    if isinstance(value, (date,)):
        return value.isoformat()
    return str(value)


def _write_csv(path: Path, columns: list[str], rows: list[list[object]]) -> None:
    lines = [",".join(columns)]
    lines += [",".join(_csv_cell(v) for v in row) for row in rows]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def _sigmoid(x: float) -> float:
    return 1.0 / (1.0 + math.exp(-x))


def build_trips(rng: random.Random) -> Dataset:
    zones = ["Gulberg", "Johar Town", "DHA", "Model Town", "Saddar", "Bahria"]
    weather = ["clear", "clear", "clear", "rain", "heat"]
    start = date(2026, 1, 5)
    rows: list[list[object]] = []
    for i in range(600):
        day = start + timedelta(days=i // 20)
        hour = 6 + (i * 7) % 18
        zone = zones[rng.randrange(len(zones))]
        distance = round(rng.uniform(1.2, 18.0), 1)
        weekday = day.weekday()
        sky = weather[rng.randrange(len(weather))]
        # Congestion is a function of hour, zone and weather -- not of a hidden
        # random draw -- so a model can learn it and a leak test can check it.
        peak = 1.6 if hour in (8, 9, 17, 18, 19) else 1.0
        zone_factor = {"Gulberg": 1.15, "Johar Town": 1.05, "DHA": 1.25,
                       "Model Town": 1.0, "Saddar": 1.1, "Bahria": 0.95}[zone]
        weather_factor = {"clear": 1.0, "rain": 1.35, "heat": 1.05}[sky]
        base = distance * 2.4 * peak * zone_factor * weather_factor
        eta = base + rng.gauss(0, 1.1) + 2.2
        accept = max(4.0, 30.0 - distance * 0.8 + rng.gauss(0, 4.0))
        rows.append([
            f"T{i + 1:04d}", day, hour, weekday, zone, sky,
            distance, round(max(1.0, accept), 1), round(max(2.0, eta), 1),
        ])
    return Dataset(
        name="raviride_trips",
        filename="raviride_trips.csv",
        description="Completed RaviRide trips with the realised ETA in minutes.",
        columns=["trip_id", "trip_date", "hour", "weekday", "zone", "weather",
                 "distance_km", "driver_accept_secs", "eta_minutes"],
        rows=rows,
    )


def build_study_support(rng: random.Random) -> Dataset:
    """Synthetic student-support records.

    The label is generated from a documented, invented relationship plus noise.
    It is not a model of any real institution, and the file contains no real
    student record. ``student_ref`` is a sequence number, not an identifier of
    a person.
    """
    gpa_bands = ["low", "mid", "high"]
    terms = ["2025-Fall", "2026-Spring"]
    rows: list[list[object]] = []
    for i in range(400):
        band = gpa_bands[rng.choices([0, 1, 2], weights=[0.25, 0.5, 0.25])[0]]
        attendance = min(1.0, max(0.35, rng.gauss({"low": 0.62, "mid": 0.78, "high": 0.9}[band], 0.1)))
        logins = max(0.0, rng.gauss({"low": 3.0, "mid": 7.0, "high": 11.0}[band], 2.5))
        submitted = min(12, max(0, round(rng.gauss({"low": 6, "mid": 9, "high": 11}[band], 2))))
        contacts = rng.choices([0, 1, 2, 3], weights=[0.5, 0.3, 0.15, 0.05])[0]
        term = terms[i % 2]
        logit = (
            -1.1
            + 4.2 * (0.6 - attendance)
            + 0.22 * (6 - logins)
            + 0.30 * (8 - submitted)
            + 0.35 * contacts
            + (0.5 if band == "low" else -0.2 if band == "high" else 0.0)
            + (0.25 if term == "2026-Spring" else 0.0)
        )
        risk = 1 if rng.random() < _sigmoid(logit) else 0
        rows.append([
            f"S{i + 1:04d}", term, band, round(attendance, 3),
            round(logins, 1), submitted, contacts, risk,
        ])
    return Dataset(
        name="study_support",
        filename="study_support.csv",
        description="Synthetic term-level support records with an invented risk label.",
        columns=["student_ref", "term", "prior_gpa_band", "attendance_rate",
                 "lms_logins_week", "assignments_submitted", "support_contacts",
                 "needs_support"],
        rows=rows,
    )


def build_equipment(rng: random.Random) -> Dataset:
    machines = [f"M{n:02d}" for n in range(1, 9)]
    rows: list[list[object]] = []
    for i in range(500):
        machine = machines[i % len(machines)]
        hours = round(rng.uniform(200, 9000), 0)
        days_service = rng.randrange(0, 220)
        temperature = round(rng.gauss(68, 6) + max(0.0, (days_service - 120)) * 0.05, 1)
        vibration = round(max(0.2, rng.gauss(2.2, 0.6) + max(0.0, hours - 6000) / 4000), 2)
        pressure = round(rng.gauss(4.2, 0.3), 2)
        logit = (
            -2.6
            + 0.9 * (vibration - 2.5)
            + 0.35 * (temperature - 70) / 2
            + 0.010 * max(0, days_service - 150)
            + 0.0003 * max(0, hours - 6500)
        )
        failure = 1 if rng.random() < _sigmoid(logit) else 0
        rows.append([
            f"R{i + 1:04d}", machine, temperature, vibration, pressure,
            int(hours), days_service, failure,
        ])
    return Dataset(
        name="equipment_sensors",
        filename="equipment_sensors.csv",
        description="Synthetic machine readings with a 7-day failure label.",
        columns=["reading_id", "machine_id", "temperature_c", "vibration_mm_s",
                 "pressure_bar", "operating_hours", "days_since_service",
                 "failure_within_7d"],
        rows=rows,
    )


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def generate(out_dir: Path = DEFAULT_OUT, seed: int = DEFAULT_SEED) -> dict[str, object]:
    rng = random.Random(seed)
    datasets = [build_trips(rng), build_study_support(rng), build_equipment(rng)]
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest: dict[str, object] = {
        "seed": seed,
        "licence": LICENCE,
        "generator": "datasets/generate.py",
        "datasets": [],
    }
    for ds in datasets:
        path = out_dir / ds.filename
        _write_csv(path, ds.columns, ds.rows)
        manifest["datasets"].append({
            "name": ds.name,
            "file": ds.filename,
            "description": ds.description,
            "rows": len(ds.rows),
            "columns": ds.columns,
            "sha256": sha256(path),
        })
    (out_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
    )
    return manifest


def check(out_dir: Path = DEFAULT_OUT) -> int:
    manifest_path = out_dir / "manifest.json"
    if not manifest_path.exists():
        print(f"no manifest at {manifest_path}; run the generator first")
        return 1
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    failures = 0
    for entry in manifest["datasets"]:
        path = out_dir / entry["file"]
        if not path.exists():
            print(f"MISSING  {entry['file']}")
            failures += 1
            continue
        actual = sha256(path)
        ok = actual == entry["sha256"]
        print(f"{'OK      ' if ok else 'CHANGED '} {entry['file']}  {entry['rows']} rows")
        failures += 0 if ok else 1
    return 1 if failures else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--check", action="store_true",
                        help="verify the files against the existing manifest")
    args = parser.parse_args()

    if args.check:
        return check(args.out)

    manifest = generate(args.out, args.seed)
    for entry in manifest["datasets"]:
        print(f"{entry['file']:26} {entry['rows']:5} rows  {entry['sha256'][:16]}...")
    print(f"manifest: {args.out / 'manifest.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
